export function getLocalizedCourse(course, language) {
  if (!course) return null;
  if (language === "pt") {
    return {
      ...course,
      formattedPrice: new Intl.NumberFormat("pt-BR", {
        style: "currency",
        currency: "BRL",
      }).format(course.price || 0),
    };
  }

  const titleLower = (course.title || "").toLowerCase();
  let title = course.title;
  let description = course.description;
  let category = course.category;
  let level = course.level;
  let producer_name = course.producer_name || course.instructor || "Nomad Team";
  let priceUSD = Math.round((course.price || 0) / 5);

  // Localize category labels
  if (category === "Nomadismo") category = "Nomadism";
  if (category === "Idiomas") category = "Languages";
  if (category === "Carreira") category = "Career";
  if (category === "Finanças") category = "Finance";

  // Map levels
  if (level === "Iniciante") level = "Beginner";
  if (level === "Intermediário") level = "Intermediate";
  if (level === "Avançado") level = "Advanced";

  if (titleLower.includes("nômade digital") || titleLower.includes("nomad")) {
    title = "The Digital Nomad: Complete Guide";
    description = "Learn the step-by-step process to break free from the office and work while traveling the world. From financial planning to choosing the best destinations.";
    category = "Nomadism";
  } else if (titleLower.includes("freelancing") || titleLower.includes("freelance")) {
    title = "Freelancing Masters";
    description = "Master remote work platforms, learn to negotiate in USD, and build a solid international freelance career.";
    category = "Career";
  } else if (titleLower.includes("inglês") || titleLower.includes("english")) {
    title = "English for Nomads";
    description = "Practical and focused English to pass immigration, rent apartments, and close international deals.";
    category = "Languages";
  } else if (titleLower.includes("investimento") || titleLower.includes("finance") || titleLower.includes("invest")) {
    title = "Global Investments";
    description = "How to protect your wealth by earning in strong currencies and investing in global markets legally and safely.";
    category = "Finance";
  }

  // Translate modules if present
  let modules = course.modules;
  if (modules && Array.isArray(modules)) {
    modules = modules.map(m => {
      let mTitle = m.title;
      const mTitleLower = (m.title || "").toLowerCase();
      if (mTitleLower.includes("introdução") || mTitleLower.includes("intro")) {
        mTitle = "Introduction to Nomadism";
      } else if (mTitleLower.includes("planejamento") || mTitleLower.includes("planning") || mTitleLower.includes("finance")) {
        mTitle = "Financial Planning & Logistics";
      } else if (mTitleLower.includes("infraestrutura") || mTitleLower.includes("infrastructure") || mTitleLower.includes("work")) {
        mTitle = "Remote Workspace & Infrastructure";
      } else if (mTitleLower.includes("destino") || mTitleLower.includes("route") || mTitleLower.includes("destin")) {
        mTitle = "Choosing Destinations & Routes";
      } else if (mTitleLower.includes("prospecção") || mTitleLower.includes("find client") || mTitleLower.includes("client")) {
        mTitle = "Finding Clients & Positioning";
      } else if (mTitleLower.includes("negociação") || mTitleLower.includes("negotiat")) {
        mTitle = "Pricing & Global Negotiation";
      } else if (mTitleLower.includes("gramática") || mTitleLower.includes("grammar")) {
        mTitle = "Immigration & Travel Vocabulary";
      } else if (mTitleLower.includes("conversação") || mTitleLower.includes("conversat")) {
        mTitle = "Closing Global Deals in English";
      } else if (mTitleLower.includes("investimento") || mTitleLower.includes("invest")) {
        mTitle = "Offshore Investing & Legal Setup";
      }
      return {
        ...m,
        title: mTitle,
      };
    });
  }

  return {
    ...course,
    title,
    description,
    category,
    level,
    producer_name,
    price: priceUSD,
    modules,
    formattedPrice: new Intl.NumberFormat("en-US", {
      style: "currency",
      currency: "USD",
    }).format(priceUSD),
  };
}

